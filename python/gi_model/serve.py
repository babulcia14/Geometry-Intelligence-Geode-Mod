"""Loopback-only API for our own weights. No telemetry, downloads or cloud.

Normal chat is generated by TinyGI. Factual tools use a transparent rule router
and an explicit evidence readout because this starter model cannot be trusted
to reproduce live IDs and names. No HTTP tools are executed by this server.
"""
import argparse
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
from pathlib import Path
import threading
import time
import torch
from .model import load_model
from .routing import plan, fold
from .evidence import render


class Server(ThreadingHTTPServer):
    daemon_threads = True
    request_queue_size = 8


class Handler(BaseHTTPRequestHandler):
    server_version = "GeometryIntelligence/1.0"

    def log_message(self, fmt, *args):
        # Do not write prompts, model output, tokens or paths to access logs.
        pass

    def setup(self):
        super().setup()
        self.connection.settimeout(15)

    def valid_origin(self):
        host = self.headers.get("Host", "").split(":")[0]
        return host in {"127.0.0.1", "localhost"} and not self.headers.get("Origin")

    def reply(self, status, value):
        payload = json.dumps(value, ensure_ascii=False).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(payload)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(payload)

    def do_GET(self):
        if not self.valid_origin():
            self.reply(403, {"error": "Only native loopback clients are allowed"}); return
        if self.path == "/health":
            self.reply(200, {"status": "ready", "model": "gi-tiny", "origin": "random-initialization",
                             "parameters": self.server.metadata["metadata"]["parameters"],
                             "training_step": self.server.metadata["step"]})
        elif self.path == "/v1/models":
            self.reply(200, {"object": "list", "data": [{"id": "gi-tiny", "object": "model", "owned_by": "local-project"}]})
        else:
            self.reply(404, {"error": "Unknown endpoint"})

    def event(self, delta, finish=None):
        payload = {"id": "gi-local", "object": "chat.completion.chunk", "model": "gi-tiny",
                   "choices": [{"index": 0, "delta": delta, "finish_reason": finish}]}
        self.wfile.write(("data: " + json.dumps(payload, ensure_ascii=False) + "\n\n").encode())
        self.wfile.flush()

    def do_POST(self):
        if self.path != "/v1/chat/completions":
            self.reply(404, {"error": "Unknown endpoint"}); return
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if not 0 < length <= 256000:
                self.reply(413, {"error": "Body size limit"}); return
            if "application/json" not in self.headers.get("Content-Type", ""):
                self.reply(415, {"error": "Expected application/json"}); return
            raw = self.rfile.read(length)
            if not self.valid_origin():
                self.reply(403, {"error": "Only native loopback clients are allowed"}); return
            body = json.loads(raw)
            messages = body["messages"]
            if not isinstance(messages, list) or not 1 <= len(messages) <= 100:
                raise ValueError("Invalid messages")
            for m in messages:
                if not isinstance(m, dict) or m.get("role") not in {"user", "assistant", "system", "tool"}:
                    raise ValueError("Invalid message role")
                if m.get("content") is not None and not isinstance(m["content"], str):
                    raise ValueError("Expected text content")
            if body.get("model") != "gi-tiny":
                self.reply(404, {"error": "Only gi-tiny is loaded; set Model to gi-tiny"}); return
            limit = int(body.get("max_tokens", 400))
            if not 1 <= limit <= 4096:
                raise ValueError("Invalid max_tokens")
            allowed = body.get("tools", [])
            if not isinstance(allowed, list) or len(allowed) > 10:
                raise ValueError("Invalid tools")
        except (ValueError, KeyError, TypeError, json.JSONDecodeError):
            self.reply(400, {"error": "Invalid chat request"}); return
        if not self.server.inference_lock.acquire(blocking=False):
            self.reply(429, {"error": "Model is busy; stop or wait for the previous request"}); return
        streaming = bool(body.get("stream", False))
        started = False
        try:
            tool = plan(messages, allowed)
            latest_user = next((m.get("content", "") for m in reversed(messages) if m["role"] == "user"), "")
            polish = any(w in fold(latest_user) for w in ["jak", "kto", "czy", "czesc", "jaki", "pokaz", "znajdz", "poziom", "stworz", "wyjasnij"])
            explicit_english = any(fold(latest_user).startswith(w) for w in ["what", "who", "how", "show", "find", "tell", "is ", "hello", "can "])
            if not polish and not explicit_english:
                polish = any("default Polish" in (m.get("content") or "") for m in messages if m["role"] == "system")
            if streaming:
                self.send_response(200)
                self.send_header("Content-Type", "text/event-stream; charset=utf-8")
                self.send_header("Cache-Control", "no-store")
                self.send_header("Connection", "close")
                self.end_headers()
                started = True
                self.close_connection = True
            if tool:
                if streaming:
                    self.event({"role": "assistant", "tool_calls": [dict(tool, index=0)]})
                    self.event({}, "tool_calls")
                else:
                    self.reply(200, {"choices": [{"message": {"role": "assistant", "content": None, "tool_calls": [tool]}, "finish_reason": "tool_calls"}]})
            else:
                evidence = render(messages, polish)
                stats = {"finish_reason": "stop"}
                if evidence is not None:
                    chunks = iter([evidence])  # No fake typewriter for already retrieved facts.
                else:
                    prefix = ("[Eksperymentalny model od zera; tekst może być niespójny i błędny.]\n" if polish else
                              "[Experimental model trained from scratch; text may be incoherent and incorrect.]\n")
                    def neural():
                        yield prefix
                        yield from self.server.model.generate(messages, max_tokens=min(limit, 700), temperature=0.65, stats=stats)
                    chunks = neural()
                text = ""
                for chunk in chunks:
                    text += chunk
                    if streaming:
                        self.event({"content": chunk})
                if streaming:
                    self.event({}, stats["finish_reason"])
                else:
                    self.reply(200, {"choices": [{"message": {"role": "assistant", "content": text}, "finish_reason": stats["finish_reason"]}]})
            if streaming:
                self.wfile.write(b"data: [DONE]\n\n"); self.wfile.flush()
        except (BrokenPipeError, ConnectionResetError, TimeoutError, ConnectionAbortedError):
            pass  # Client cancellation ends generation on the next attempted write.
        except Exception as exc:
            print(f"Request failed: {type(exc).__name__}", flush=True)
            if not started:
                self.reply(500, {"error": "Local model failed; check the server console"})
        finally:
            self.server.inference_lock.release()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--checkpoint", default="models/gi-tiny/model.pt")
    p.add_argument("--port", type=int, default=18765)
    p.add_argument("--threads", type=int, default=4)
    args = p.parse_args()
    if not 1024 <= args.port <= 65535 or not 1 <= args.threads <= 64:
        p.error("Invalid port/thread count")
    if not Path(args.checkpoint).is_file():
        p.error("Missing inference weights. Unpack the full release or run Train_AI.cmd from the project root.")
    torch.set_num_threads(args.threads)
    model, metadata = load_model(args.checkpoint)
    server = Server(("127.0.0.1", args.port), Handler)
    server.model, server.metadata = model, metadata
    server.inference_lock = threading.Lock()
    print(f"GI ready: http://127.0.0.1:{args.port}/v1 ; model=gi-tiny ; training step={metadata['step']}", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
